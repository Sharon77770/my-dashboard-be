const {JSDOM}=require('jsdom'),fs=require('node:fs'),assert=require('node:assert/strict');
const dom=new JSDOM('<body data-account="fixture"><div id="communications"></div><dialog id="editor-dialog"><div id="editor-fields"></div></dialog></body>',{runScripts:'outside-only',url:'http://localhost'});
const w=dom.window,d=w.document,calls=[];
const message={accountId:'gmail',provider:'GMAIL',id:'m1',conversationId:'original-thread',sender:'Sender',text:'<img src=x onerror=alert(1)>',timestamp:null,attachments:[]};
for(const file of ['ui.js','live-dom.js','communications.js'])w.eval(fs.readFileSync('src/main/resources/static/js/'+file,'utf8'));
d.querySelector('dialog').close=function(){this.dispatchEvent(new w.Event('close'));};
const api=async path=>{
  calls.push(path);
  if(path.endsWith('/accounts'))return [{id:'gmail',provider:'GMAIL',label:'Gmail fixture',capabilities:['READ','SEND','SEARCH']},{id:'slack',provider:'SLACK',label:'Slack fixture',capabilities:['READ','SEND']}];
  if(path.endsWith('/providers')||path.endsWith('/actions'))return [];
  if(path.endsWith('/conversations'))return {items:[],nextCursor:''};
  if(path.includes('/message-search?'))return path.includes('cursor=next')?{items:[message,{...message,id:'m2',text:'Second result'}],nextCursor:''}:{items:[message],nextCursor:'next'};
  if(path.includes('/messages?'))return {items:[message],nextCursor:''};
  if(path.startsWith('/communications/search?'))return [message];
  throw Error(path);
};
w.WorkspaceCommunications.init({api,escape:w.WorkspaceUI.escape,toast:message=>{throw Error(message);},editor:(title,html)=>{d.querySelector('#editor-fields').innerHTML=html;}});
const tick=()=>new Promise(resolve=>setTimeout(resolve,20));
(async()=>{
  await w.WorkspaceCommunications.open('communications');
  const form=d.querySelector('[data-comm-search]'),scope=form.querySelector('select');
  assert.deepEqual([...scope.options].map(option=>option.value),['','gmail']);
  scope.value='gmail';scope.dispatchEvent(new w.Event('change',{bubbles:true}));
  form.querySelector('input').value='from:a@example.test is:unread';
  form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));await tick();
  assert.ok(calls.some(path=>path.includes('/accounts/gmail/message-search?query=from%3Aa%40example.test%20is%3Aunread&cursor=')));
  assert.equal(d.querySelector('[data-comm-search-results] img'),null);
  d.querySelector('[data-comm-search-more]').click();await tick();
  assert.equal(d.querySelectorAll('[data-comm-search-results] article').length,2);
  assert.equal(d.querySelector('[data-comm-search-more]'),null);
  d.querySelector('[data-comm-search-open="0"]').click();await tick();
  assert.ok(calls.some(path=>path.includes('/messages?conversationId=original-thread')));
  assert.equal(d.querySelector('.comm-message img'),null);
  scope.value='';form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));await tick();
  assert.ok(calls.some(path=>path.startsWith('/communications/search?')));
  assert.equal(calls.filter(path=>path.includes('/confirmation')).length,0);
  console.log('PASS Communications search: capability scopes, provider paging/dedup, XSS, original conversation navigation and local cache fallback.');
  w.close();
})().catch(error=>{console.error(error);w.close();process.exitCode=1;});
